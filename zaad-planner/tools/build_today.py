#!/usr/bin/env python3
"""Write ../../zaad/data.js: the content of the planner that the free web page "Zaad today" shows.

  python3 tools/build_today.py

The page shows today's name of Allah (and how to live by it), a hadith in Arabic and English, and the Sunnah of the week,
using the same lists and the same rules as the planner.
"""
import importlib.util, json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "src"))
spec = importlib.util.spec_from_file_location("zbuild", os.path.join(ROOT, "build.py"))
B = importlib.util.module_from_spec(spec)
spec.loader.exec_module(B)


def entry(key, label, text, ref):
    return {"label": label, "ar": B.AR.get(B.AR_KEY.get(key, key), ""), "en": re.sub(r"\s+", " ", text), "ref": B.nref(key, ref)}


ev = {e[0]: e for e in B.EVIDENCE + B.SEASONAL}
foot = [entry(k, label, text, ref) for label, text, ref, k in B.FOOT]
ramadan = [entry(k, ev[k][1], ev[k][2], ev[k][3]) for k in ("ramadan", "taraweeh", "suhoor", "iftar")]
ramadan.append({"label": "The dua of Laylat al-Qadr", "ar": B.AR["afuww"], "en": "O Allah, You are Pardoning and love to pardon, so pardon me.",
                "ref": "'A'ishah · at-Tirmidhi 3513"})
friday = [entry(k, ev[k][1], ev[k][2], ev[k][3]) for k in ("kahf", "hour", "jumuah")]
data = {
    "names": [[t, a, m, B.NAME_LIVE[i]] for i, (t, a, m) in enumerate(B.NAMES)],
    "foot": foot, "ramadan": ramadan, "friday": friday,
    "sunnah": [[t, r] for t, r, *_ in B.SUNNAH_WEEK],
}
out = os.path.join(ROOT, "..", "zaad", "data.js")
open(out, "w", encoding="utf-8").write("// Generated by zaad-planner/tools/build_today.py. Do not edit by hand.\nconst ZAAD = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"{len(data['names'])} names, {len(foot)} hadith, {len(ramadan)} Ramadan, {len(friday)} Friday, {len(data['sunnah'])} Sunnahs -> {out}")
