'use strict';

// One-off generator: turns src/main/licenseKeyHashes.json into
// cloud/seed_license_keys.sql. Not run automatically — re-run manually if
// licenseKeyHashes.json ever changes (e.g. a future batch of new keys).

const fs = require('fs');
const path = require('path');

const hashes = require(path.join(__dirname, '..', 'src', 'main', 'licenseKeyHashes.json'));

const header = `-- Seeds the 1000 product keys already generated by scripts/generate-keys.js
-- (see src/main/licenseKeyHashes.json) into license_keys, so
-- activate_license_key in schema.sql has real keys to check against. Run
-- once, after schema.sql, in Supabase's SQL Editor. Safe to re-run: "on
-- conflict do nothing" skips hashes already present instead of erroring.
-- Regenerated by scripts/gen-seed-sql.js.

insert into public.license_keys (key_hash) values
`;

const values = hashes.map((h, i) => '  (\'' + h + '\')' + (i === hashes.length - 1 ? '' : ','));
const sql = header + values.join('\n') + '\non conflict (key_hash) do nothing;\n';

fs.writeFileSync(path.join(__dirname, '..', 'cloud', 'seed_license_keys.sql'), sql);
console.log(`wrote ${hashes.length} rows`);
