'use strict';

// Generates a batch of new NOOR-XXXXX-XXXXX-XXXXX product keys that expire
// a fixed number of days after activation (see the duration_days/expires_at
// columns and activate_license_key in cloud/schema.sql) — for a promo or
// time-limited tier, distinct from the original lifetime-key batch (see
// generate-keys.js, which still only makes lifetime keys).
//
// Writes the plaintext keys to a local file (never committed) and a seed
// SQL file (cloud/seed_license_keys_<days>day.sql) that inserts each key's
// hash + duration_days — run that file once in Supabase's SQL Editor to
// make the keys real. No licenseKeyHashes.json involvement: that file is a
// legacy fallback list for the original lifetime batch and isn't read by
// license.js/License.kt at all anymore — Supabase is the only source of
// truth for activation now.
//
// Usage: node scripts/generate-timed-keys.js <durationDays> [count] [outputFile]
// Example: node scripts/generate-timed-keys.js 29 10

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const DURATION_DAYS = Number(process.argv[2]);
const COUNT = Number(process.argv[3]) || 10;
const OUTPUT_FILE = process.argv[4] || path.join(__dirname, '..', `new-product-keys-${DURATION_DAYS}day.txt`);
const SEED_FILE = path.join(__dirname, '..', 'cloud', `seed_license_keys_${DURATION_DAYS}day.sql`);

if (!Number.isInteger(DURATION_DAYS) || DURATION_DAYS <= 0) {
  console.error('Usage: node scripts/generate-timed-keys.js <durationDays> [count] [outputFile]');
  process.exit(1);
}

// Same alphabet as generate-keys.js: excludes visually ambiguous characters
// (0/O, 1/I/L) so a key is easy to read back correctly from a screen or printout.
const ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';

function randomGroup(length) {
  let out = '';
  for (let i = 0; i < length; i++) {
    out += ALPHABET[crypto.randomInt(0, ALPHABET.length)];
  }
  return out;
}

function hashOf(canonicalKey) {
  return crypto.createHash('sha256').update(canonicalKey).digest('hex');
}

function main() {
  const seen = new Set();
  const keys = [];
  const hashes = [];
  while (keys.length < COUNT) {
    const key = `NOOR-${randomGroup(5)}-${randomGroup(5)}-${randomGroup(5)}`;
    const hash = hashOf(key);
    if (seen.has(hash)) continue; // astronomically unlikely, but stay correct
    seen.add(hash);
    keys.push(key);
    hashes.push(hash);
  }

  fs.writeFileSync(OUTPUT_FILE, keys.join('\n') + '\n');

  const header =
    `-- Seeds ${hashes.length} time-limited (${DURATION_DAYS}-day) product keys, generated by\n` +
    `-- scripts/generate-timed-keys.js. Run once, after schema.sql (which must already\n` +
    `-- have the duration_days/expires_at columns), in Supabase's SQL Editor. Safe to\n` +
    `-- re-run: "on conflict do nothing" skips hashes already present instead of erroring.\n` +
    `-- Each key's access window starts the moment it's first activated, not now.\n\n` +
    `insert into public.license_keys (key_hash, duration_days) values\n`;
  const values = hashes.map((h, i) => `  ('${h}', ${DURATION_DAYS})` + (i === hashes.length - 1 ? '' : ','));
  const sql = header + values.join('\n') + '\non conflict (key_hash) do nothing;\n';
  fs.writeFileSync(SEED_FILE, sql);

  console.log(`Generated ${keys.length} new ${DURATION_DAYS}-day keys.`);
  console.log(`Plaintext keys written to: ${OUTPUT_FILE} (keep this safe — do not commit it)`);
  console.log(`Seed SQL written to: ${SEED_FILE}`);
  console.log(`Next: run schema.sql (for the duration_days/expires_at columns) then ${path.basename(SEED_FILE)} in Supabase's SQL Editor.`);
}

main();
