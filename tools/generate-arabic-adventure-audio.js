#!/usr/bin/env node
/* Generates MP3 pronunciation clips for Arabic Adventure using Google
 * Cloud Text-to-Speech, and writes the manifest arabic-adventure.html
 * uses to look up a pre-recorded file for a given speakArabic()/
 * speakEnglish() text before falling back to the browser's own speech
 * synthesis.
 *
 * Re-run this whenever the curriculum data in
 * data/arabic-adventure-world1.js changes — it skips any text whose
 * audio file already exists, so it only synthesizes what's new.
 *
 *   GOOGLE_TTS_API_KEY=xxx node tools/generate-arabic-adventure-audio.js
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const API_KEY = process.env.GOOGLE_TTS_API_KEY;
if(!API_KEY){
  console.error('Set GOOGLE_TTS_API_KEY first.');
  process.exit(1);
}

const AR_VOICE = 'ar-XA-Chirp3-HD-Algenib';
const EN_VOICE = 'en-US-Chirp3-HD-Achird';

const ROOT = path.join(__dirname, '..');
global.window = global;
require(path.join(ROOT, 'data', 'arabic-adventure-world1.js'));
const DATA = global.ARABIC_ADVENTURE_WORLD1;

const AR_DIR = path.join(ROOT, 'audio', 'arabic-adventure', 'ar');
const EN_DIR = path.join(ROOT, 'audio', 'arabic-adventure', 'en');
fs.mkdirSync(AR_DIR, { recursive: true });
fs.mkdirSync(EN_DIR, { recursive: true });

function slug(text){
  return crypto.createHash('sha1').update(text).digest('hex').slice(0, 16);
}

async function synthesize(text, voice, langCode){
  const res = await fetch('https://texttospeech.googleapis.com/v1/text:synthesize?key=' + API_KEY, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      input: { text },
      voice: { languageCode: langCode, name: voice },
      audioConfig: { audioEncoding: 'MP3' }
    })
  });
  const data = await res.json();
  if(!data.audioContent) throw new Error('TTS failed for "' + text + '": ' + JSON.stringify(data).slice(0, 300));
  return Buffer.from(data.audioContent, 'base64');
}

async function main(){
  /* Map key = exact text the app passes to speakArabic()/speakEnglish();
     map value = what's actually synthesized. These differ only for a
     bare letter glyph, which should be read as its full name (e.g. "ا"
     is spoken as "أَلِف"), not attempted as a word on its own. */
  const arEntries = new Map();
  const enEntries = new Map();

  DATA.letters.forEach(l => {
    arEntries.set(l.letter, l.name);
    arEntries.set(l.word, l.word);
    enEntries.set(l.english, l.english);
  });
  Object.values(DATA.vocabModules).forEach(mod => {
    mod.words.forEach(w => {
      arEntries.set(w.word, w.word);
      enEntries.set(w.english, w.english);
    });
  });
  Object.values(DATA.stories).forEach(story => {
    story.pages.forEach(p => arEntries.set(p.text, p.text));
  });

  const manifest = { ar: {}, en: {} };

  async function fill(entries, dir, voice, langCode, urlPrefix, label, out){
    let i = 0;
    for(const [key, speakText] of entries){
      i++;
      const file = slug(key) + '.mp3';
      const full = path.join(dir, file);
      if(!fs.existsSync(full)){
        process.stdout.write(label + ' ' + i + '/' + entries.size + ': ' + speakText + ' ... ');
        const buf = await synthesize(speakText, voice, langCode);
        fs.writeFileSync(full, buf);
        console.log('ok');
      }
      out[key] = urlPrefix + file;
    }
  }

  await fill(arEntries, AR_DIR, AR_VOICE, 'ar-XA', 'audio/arabic-adventure/ar/', 'AR', manifest.ar);
  await fill(enEntries, EN_DIR, EN_VOICE, 'en-US', 'audio/arabic-adventure/en/', 'EN', manifest.en);

  fs.writeFileSync(
    path.join(ROOT, 'data', 'arabic-adventure-audio-manifest.js'),
    '/* Generated by tools/generate-arabic-adventure-audio.js — do not hand-edit. */\n' +
    'window.ARABIC_ADVENTURE_AUDIO_MANIFEST = ' + JSON.stringify(manifest, null, 2) + ';\n'
  );
  console.log('Manifest written:', Object.keys(manifest.ar).length, 'ar entries,', Object.keys(manifest.en).length, 'en entries');
}

main().catch(err => { console.error(err); process.exit(1); });
