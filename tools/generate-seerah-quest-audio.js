#!/usr/bin/env node
/* Generates MP3 narration clips for Seerah Quest using Google Cloud
 * Text-to-Speech, and writes the manifest kids-seerah-quest.html uses to
 * look up a pre-recorded file for a given speakEnglish()/speakArabic()
 * text before falling back to the browser's own speech synthesis.
 *
 * Re-run this whenever data/kids-seerah-quest-data.js changes -- it
 * skips any text whose audio file already exists, so it only
 * synthesizes what's new.
 *
 *   GOOGLE_TTS_API_KEY=xxx node tools/generate-seerah-quest-audio.js
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const API_KEY = process.env.GOOGLE_TTS_API_KEY;
if(!API_KEY){
  console.error('Set GOOGLE_TTS_API_KEY first.');
  process.exit(1);
}

const AR_VOICE = 'ar-XA-Chirp3-HD-Algenib';
const EN_VOICE = 'en-US-Chirp3-HD-Achird';

const ROOT = path.join(__dirname, '..');
global.window = global;
require(path.join(ROOT, 'data', 'kids-seerah-quest-data.js'));
const SEERAH = global.SEERAH;

const AR_DIR = path.join(ROOT, 'audio', 'kids-seerah-quest', 'ar');
const EN_DIR = path.join(ROOT, 'audio', 'kids-seerah-quest', 'en');
fs.mkdirSync(AR_DIR, { recursive: true });
fs.mkdirSync(EN_DIR, { recursive: true });

function slug(text){
  return crypto.createHash('sha1').update(text).digest('hex').slice(0, 16);
}

async function synthesize(text, voice, langCode){
  const res = await fetch('https://texttospeech.googleapis.com/v1/text:synthesize?key=' + API_KEY, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      input: { text },
      voice: { languageCode: langCode, name: voice },
      audioConfig: { audioEncoding: 'MP3' }
    })
  });
  const data = await res.json();
  if(!data.audioContent) throw new Error('TTS failed for "' + text + '": ' + JSON.stringify(data).slice(0, 300));
  return Buffer.from(data.audioContent, 'base64');
}

/* These fixed instruction lines live as literal strings inside
   buildLesson()/renderStep() in kids-seerah-quest.html, not in the data
   file, so they're listed here by hand -- keep this list in sync if
   those strings ever change. */
const FIXED_EN_LINES = [
  'Listen carefully to what happened — the games come after.',
  'Read every answer, then tap the one that is right.',
  'Pick up the correct answer with your finger or mouse and drag it into the box.',
  'Tap a card on the left, then tap the card on the right that goes with it.',
  'Think about what happened first, and tap them one by one in order.',
  'Listen to each sentence and say whether it is true or false.',
  'Every story from the Seerah has something we can take into our own lives.'
];

async function main(){
  const arEntries = new Map();
  const enEntries = new Map();

  FIXED_EN_LINES.forEach(t => enEntries.set(t, t));

  SEERAH.forEach(S => {
    enEntries.set(S.story, S.story);
    if(S.benefit) enEntries.set(S.benefit, S.benefit);
    S.picks.forEach(p => enEntries.set(p.q, p.q));
    enEntries.set(S.order.prompt, S.order.prompt);
    S.tf.forEach(t => enEntries.set(t.s, t.s));
    if(S.arabic) arEntries.set(S.arabic, S.arabic);
    if(S.quran){
      arEntries.set(S.quran.arabic, S.quran.arabic);
      enEntries.set(S.quran.translation, S.quran.translation);
    }
  });

  const manifest = { ar: {}, en: {} };

  async function fill(entries, dir, voice, langCode, urlPrefix, label, out){
    let i = 0;
    for(const [key, speakText] of entries){
      i++;
      const file = slug(key) + '.mp3';
      const full = path.join(dir, file);
      if(!fs.existsSync(full)){
        process.stdout.write(label + ' ' + i + '/' + entries.size + ': ' + speakText.slice(0, 60) + ' ... ');
        const buf = await synthesize(speakText, voice, langCode);
        fs.writeFileSync(full, buf);
        console.log('ok');
      }
      out[key] = urlPrefix + file;
    }
  }

  await fill(arEntries, AR_DIR, AR_VOICE, 'ar-XA', 'audio/kids-seerah-quest/ar/', 'AR', manifest.ar);
  await fill(enEntries, EN_DIR, EN_VOICE, 'en-US', 'audio/kids-seerah-quest/en/', 'EN', manifest.en);

  fs.writeFileSync(
    path.join(ROOT, 'data', 'kids-seerah-quest-audio-manifest.js'),
    '/* Generated by tools/generate-seerah-quest-audio.js -- do not hand-edit. */\n' +
    'window.SEERAH_AUDIO_MANIFEST = ' + JSON.stringify(manifest, null, 2) + ';\n'
  );
  console.log('Manifest written:', Object.keys(manifest.ar).length, 'ar entries,', Object.keys(manifest.en).length, 'en entries');
}

main().catch(err => { console.error(err); process.exit(1); });
